/** Board members, in the order they appear on the Team page. */
export const board = team.filter((m) => m.rank === 'board')

/** Every department leader. */
export const leads = team.filter((m) => m.rank === 'lead')

export const advisors = team.filter((m) => m.rank === 'advisor')

const rankOrder = { board: 0, lead: 1, member: 2, advisor: 3 } as const

/** Everyone assigned to a department, leaders first then alphabetical. */
export function membersOf(slug: string): TeamMember[] {
  return team
    .filter((m) => m.department === slug)
    .sort((a, b) => rankOrder[a.rank] - rankOrder[b.rank] || a.name.localeCompare(b.name))
}

export function leadsOf(slug: string): TeamMember[] {
  return team.filter((m) => m.department === slug && m.rank === 'lead')
}

/** Initials used by the photo placeholder. */
export function initials(name: string): string {
  const parts = name.split(' ').filter(Boolean)
  if (parts.length === 0) return '?'
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase()
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase()
}
